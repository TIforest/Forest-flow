import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
const base = 'http://127.0.0.1:5173';
async function call(path, actor = 'coord', method = 'GET', body) {
  const response = await fetch(`${base}/api/${path}`, {
    method,
    headers: {
      Origin: base,
      'X-Demo-User': actor,
      'Content-Type': 'application/json',
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  return { status: response.status, data: await response.json() };
}
const draft = {
  name: 'Integrante temporário de teste',
  job: 'Validação local',
  role: 'member',
  color: '#b83869',
};
let id;
let taskId;
try {
  assert.equal((await call('users', 'bruno', 'POST', draft)).status, 403);
  assert.equal(
    (await call('users', 'coord', 'POST', { ...draft, name: '  ' })).status,
    400,
  );
  assert.equal(
    (await call('users', 'coord', 'POST', { ...draft, color: 'invalid' }))
      .status,
    400,
  );
  assert.equal(
    (await call('users', 'coord', 'POST', { ...draft, role: 'admin' })).status,
    400,
  );
  const created = await call('users', 'coord', 'POST', draft);
  assert.equal(created.status, 201);
  id = created.data.id;
  assert.ok(
    (await call('users')).data.some(
      (u) => u.id === id && u.color === draft.color,
    ),
  );
  assert.equal(
    (await call(`users/${id}`, 'bruno', 'PATCH', draft)).status,
    403,
  );
  const updated = await call(`users/${id}`, 'coord', 'PATCH', {
    ...draft,
    job: 'Cargo atualizado',
    color: '#008578',
    role: 'coordinator',
  });
  assert.equal(updated.status, 200);
  assert.equal(updated.data.job, 'Cargo atualizado');
  assert.equal(updated.data.color, '#008578');
  assert.equal(updated.data.role, 'coordinator');
  assert.equal(
    (await call('users/coord', 'coord', 'PATCH', { ...draft, role: 'member' }))
      .status,
    409,
  );
  const createdTask = await call('tasks', 'coord', 'POST', {
    title: 'Teste de delegação para novo integrante',
    description: '',
    assignee_id: id,
    week: '2099-01-04',
    due_date: '',
    priority: 'normal',
    restricted: true,
  });
  assert.equal(createdTask.status, 201);
  taskId = createdTask.data.id;
  assert.ok(
    (await call('tasks?week=2099-01-04', id)).data.some((t) => t.id === taskId),
  );
  console.log(
    '14 verificações passaram: cadastro, edição, cores, perfis, validação, permissões e delegação.',
  );
} finally {
  // Only remove records generated by this local test, never existing members.
  const uuid = /^[0-9a-f-]{36}$/;
  if (id && uuid.test(id)) {
    let sql = '';
    if (taskId && uuid.test(taskId))
      sql += `DELETE FROM task_weeks WHERE task_id='${taskId}'; DELETE FROM comments WHERE task_id='${taskId}'; DELETE FROM events WHERE task_id='${taskId}'; DELETE FROM tasks WHERE id='${taskId}'; `;
    sql += `DELETE FROM users WHERE id='${id}';`;
    execFileSync(
      process.execPath,
      [
        'node_modules/wrangler/bin/wrangler.js',
        'd1',
        'execute',
        'DB',
        '--local',
        '--command',
        sql,
      ],
      { stdio: 'pipe' },
    );
    console.log('Registros temporários removidos do D1 local.');
  }
}
